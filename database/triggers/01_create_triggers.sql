CREATE OR REPLACE TRIGGER TRG_HANDOVER_DATE
BEFORE INSERT OR UPDATE OF status
ON HANDOVER_RECORDS
FOR EACH ROW
BEGIN
    IF :NEW.status = 'COMPLETED'
       AND :NEW.handover_date IS NULL THEN
        :NEW.handover_date := SYSDATE;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_HANDOVER_ITEM_STATUS
AFTER UPDATE OF status
ON HANDOVER_RECORDS
FOR EACH ROW
BEGIN
    IF :NEW.status = 'COMPLETED'
       AND :OLD.status <> 'COMPLETED' THEN

        UPDATE ITEMS
        SET status = 'RETURNED'
        WHERE item_id = :NEW.item_id;

    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_CLAIM_DATE
BEFORE INSERT
ON CLAIMS
FOR EACH ROW
BEGIN
    IF :NEW.claim_date IS NULL THEN
        :NEW.claim_date := SYSDATE;
    END IF;
END;
/
CREATE TABLE CUSTODY_RECORDS (
    custody_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    item_id NUMBER NOT NULL,
    officer_id NUMBER NOT NULL,
    from_location VARCHAR2(100),
    to_location VARCHAR2(100) NOT NULL,
    custody_date DATE DEFAULT SYSDATE NOT NULL,
    notes VARCHAR2(255),
    CONSTRAINT pk_custody_records PRIMARY KEY (custody_id),
    CONSTRAINT fk_custody_item FOREIGN KEY (item_id) REFERENCES ITEMS(item_id),
    CONSTRAINT fk_custody_officer FOREIGN KEY (officer_id) REFERENCES USERS(user_id)
);
CREATE TABLE ITEMS (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER NOT NULL,
    category_id NUMBER NOT NULL,
    item_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    secret_question VARCHAR2(255) NOT NULL,
    secret_answer_hash VARCHAR2(255) NOT NULL,
    photo VARCHAR2(255),
    location_found VARCHAR2(100) NOT NULL,
    date_found DATE NOT NULL,
    status VARCHAR2(20) DEFAULT 'PENDING_REVIEW' NOT NULL,
    CONSTRAINT pk_items PRIMARY KEY (item_id),
    CONSTRAINT fk_items_user FOREIGN KEY (user_id) REFERENCES USERS(user_id),
    CONSTRAINT fk_items_category FOREIGN KEY (category_id) REFERENCES CATEGORIES(category_id),
    CONSTRAINT chk_items_status CHECK (status IN ('PENDING_REVIEW', 'ACTIVE', 'IN_CUSTODY', 'CLAIM_APPROVED', 'RETURNED'))
);
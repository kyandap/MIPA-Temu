CREATE TABLE CLAIMS (
    claim_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    item_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    attempt_count NUMBER DEFAULT 0 NOT NULL,
    claim_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    claim_date DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_claims PRIMARY KEY (claim_id),
    CONSTRAINT fk_claims_item FOREIGN KEY (item_id) REFERENCES ITEMS(item_id),
    CONSTRAINT fk_claims_user FOREIGN KEY (user_id) REFERENCES USERS(user_id),
    CONSTRAINT chk_claims_status CHECK (claim_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT chk_claims_attempt CHECK (attempt_count >= 0)
);
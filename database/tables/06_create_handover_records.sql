CREATE TABLE HANDOVER_RECORDS (
    handover_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    item_id NUMBER NOT NULL,
    officer_id NUMBER NOT NULL,
    owner_id NUMBER NOT NULL,
    handover_code_hash VARCHAR2(255) NOT NULL,
    handover_date DATE,
    status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT pk_handover_records PRIMARY KEY (handover_id),
    CONSTRAINT fk_handover_item FOREIGN KEY (item_id) REFERENCES ITEMS(item_id),
    CONSTRAINT fk_handover_officer FOREIGN KEY (officer_id) REFERENCES USERS(user_id),
    CONSTRAINT fk_handover_owner FOREIGN KEY (owner_id) REFERENCES USERS(user_id),
    CONSTRAINT chk_handover_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED'))
);